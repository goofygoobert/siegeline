// Write the offline service worker into dist/ with a precache list of the shell, and a versioned cache name.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { execSync } from "node:child_process";
const dist = new URL("../dist/", import.meta.url).pathname;
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push(relative(dist, p)); } })(dist);
let ver = Date.now().toString(36); try { ver = execSync("git rev-parse --short HEAD").toString().trim() + "-" + ver; } catch {}
// shell + region 1 art + audio are precached so the game works offline after the first visit
const pre = files.filter((f) => !f.endsWith(".map") && !f.startsWith("worlds/") && f !== "sw.js" && !/STATUS\.md$/.test(f));
const total = pre.reduce((n, f) => n + statSync(join(dist, f)).size, 0);
const sw = `// generated by tools/postbuild.mjs
const CACHE = "siegeline-${ver}";
const PRE = ${JSON.stringify(["./", ...pre])};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", (e) => {
  const r = e.request; if (r.method !== "GET" || new URL(r.url).origin !== location.origin) return;
  if (r.mode === "navigate") {
    // the page: network first so updates arrive at once; cached copy only when offline
    e.respondWith(fetch(r).then((res) => { const cp = res.clone(); caches.open(CACHE).then((c) => c.put("./", cp)); return res; })
      .catch(() => caches.match("./")));
    return;
  }
  // versioned files (hashed code, art, audio): cache first, fill the cache from the network
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((hit) => hit || fetch(r).then((res) => {
    if (res.ok) { const cp = res.clone(); caches.open(CACHE).then((c) => c.put(r, cp)); }
    return res;
  })));
});
`;
writeFileSync(join(dist, "sw.js"), sw);
console.log(`sw.js: ${pre.length} files precached, ${(total / 1024 / 1024).toFixed(2)} MB`);
