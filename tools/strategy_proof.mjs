// Strategy proof for docs/balance.md (owner's part 3 checks). For every region 1 stage, with the crew a player can have
// by then (free recruits plus Tavern crew already offered):
//   - the intended loadout, the listed wrong loadout, and RANDOM random loadouts, each N battles (average test player,
//     no upgrades);
//   - the wrong loadout again with upgrades two tiers ahead (crew level 6, fort/cannon 6) — must stay under 50%;
// then across the region:
//   - no single loadout wins every stage (each of the 56 five-crew loadouts of the full region 1 roster is run on every stage);
//   - every crew member appears in 10-90% of winning loadouts (random loadouts that win at least half their battles).
// usage: node tools/strategy_proof.mjs [N=30] [RANDOM=24]  -> prints markdown, writes docs/balance-strategy.md
import { loadContent } from "./content_node.mjs";
import { createBattle, step } from "../src/sim/battle.js";
import { makeBot } from "../src/sim/bot.js";
import { rng } from "../src/sim/stats.js";
import { kit, ROSTER } from "./loadouts.mjs";
import { writeFileSync } from "node:fs";

const C = loadContent(); const N = +(process.argv[2] || 30), RANDOM = +(process.argv[3] || 24);
const stages = C.stages;
const UP = { lv: 6, keep: 6, ballista: 6, energyMax: 3, energyRegen: 3, hero: 5, ab: 5 };
const upProg = () => { const L = {}; for (const u of C.units.units) L[u.id] = UP.lv; return { unitLevels: L, keep: UP.keep, ballista: UP.ballista, energyMax: UP.energyMax, energyRegen: UP.energyRegen, hero: UP.hero, abilities: { ember_rain: UP.ab, rally: UP.ab }, skills: {} }; };

/** Crew a player can field at stage k: the starters, every free recruit from stages before k, and Tavern crew offered before k. */
function crewAt(k) {
  const have = ["ashguard", "torchbow"];
  for (let i = 0; i < k; i++) for (const u of [...stages[i].unlocks, ...(stages[i].tavern || [])]) if (C.units.units.some((x) => x.id === u) && !have.includes(u)) have.push(u);
  return have;
}
function rate(k, crew, prog = {}, n = N, seed0 = 500) {
  let w = 0;
  for (let i = 0; i < n; i++) {
    const B = createBattle(C, { ...stages[k], available: crew, ...kit(k) }, prog, seed0 + i * 7919); const bot = makeBot({ skill: 0.6 });
    while (!B.result && B.t < 900) { bot(B); step(B); B.events.length = 0; }
    if (B.result === "win") w++;
  }
  return w / n;
}
function combos(arr, k) { const out = []; const go = (i, cur) => { if (cur.length === k) { out.push(cur.slice()); return; } for (let j = i; j < arr.length; j++) { cur.push(arr[j]); go(j + 1, cur); cur.pop(); } }; go(0, []); return out; }

const t0 = Date.now(), pct = (x) => Math.round(x * 100) + "%", name = (id) => C.units.units.find((u) => u.id === id).name;
const rows = [], winners = [];
for (let k = 0; k < stages.length; k++) {
  const st = stages[k], plan = ROSTER.stages[k], pool = crewAt(k), size = Math.min(st.slots || 5, pool.length);
  const right = rate(k, plan.right), wrong = rate(k, plan.wrongIds), wrongUp = rate(k, plan.wrongIds, upProg());
  // random loadouts from what the player has (deterministic sample)
  const R = rng(1234 + k), all = combos(pool, size), sample = all.length <= RANDOM ? all : Array.from({ length: RANDOM }, () => all[Math.floor(R() * all.length)]);
  const rr = sample.map((lo) => { const r = rate(k, lo, {}, Math.max(10, N >> 1)); if (r >= 0.5) winners.push(lo); return r; });
  const rnd = rr.reduce((a, b) => a + b, 0) / rr.length;
  rows.push({ id: st.id, name: st.name, right, wrong, wrongUp, rnd, rmin: Math.min(...rr), rmax: Math.max(...rr), plan });
  process.stderr.write(`${st.id} right ${pct(right)} wrong ${pct(wrong)} wrong+up ${pct(wrongUp)} random ${pct(rnd)}  (${((Date.now() - t0) / 1000).toFixed(0)}s)\n`);
}
// one loadout for everything? every 5-of-8 loadout of the full region roster on every stage
const full = ROSTER.crew.filter((c) => c.region === 1).map((c) => c.id), universal = [];
for (const lo of combos(full, 5)) {
  let worst = 1;
  for (let k = 0; k < stages.length && worst >= 0.5; k++) worst = Math.min(worst, rate(k, lo.slice(0, stages[k].slots || 5), {}, 10));
  universal.push({ lo, worst });
}
universal.sort((a, b) => b.worst - a.worst);
const share = {}; for (const id of full) share[id] = winners.filter((lo) => lo.includes(id)).length / Math.max(1, winners.length);

let md = `Generated by \`node tools/strategy_proof.mjs ${N} ${RANDOM}\`: average test player (skill 0.6), no upgrades unless stated, ${N} battles per loadout (random loadouts ${Math.max(10, N >> 1)} each). The crew on offer at each stage is what a player has by then (free recruits and Tavern crew already offered).\n\n`;
md += "| Stage | Intended loadout | Win | Sensible wrong loadout | Win | Wrong, upgraded 2 tiers | Gap | Random loadouts: avg (min–max) | Pass |\n|---|---|--:|---|--:|--:|--:|---|:-:|\n";
let pass = 0;
for (const r of rows) {
  const gap = r.right - r.wrong, ok = gap >= 0.4;
  if (ok) pass++;
  md += `| ${r.name} | ${r.plan.right.map(name).join(", ")} | ${pct(r.right)} | ${r.plan.wrongIds.map(name).join(", ")} | ${pct(r.wrong)} | ${pct(r.wrongUp)} | ${Math.round(gap * 100)} | ${pct(r.rnd)} (${pct(r.rmin)}–${pct(r.rmax)}) | ${ok ? "yes" : "**no**"} |\n`;
}
const best = universal[0];
md += `\n**Right beats wrong by 40+ points:** ${pass} of ${rows.length} stages.\n\n`;
md += `**Upgrades cannot brute-force a stage** (my own extra target: wrong loadout with crew level 6, fort and cannon level 6, under 50%): ${rows.filter((r) => r.wrongUp < 0.5).length} of ${rows.length} stages.\n\n`;
md += `**No loadout wins every stage:** the best of the 56 five-crew loadouts (${best.lo.map(name).join(", ")}) wins ${pct(best.worst)} on its worst stage — ${best.worst < 0.5 ? "passes" : "**fails**"} (needs under 50% somewhere).\n\n`;
md += `**Every crew member in 10–90% of winning loadouts** (${winners.length} random loadouts won at least half their battles):\n\n| Crew | Share of winning loadouts | Pass |\n|---|--:|:-:|\n`;
for (const id of full) md += `| ${name(id)} | ${pct(share[id])} | ${share[id] >= 0.1 && share[id] <= 0.9 ? "yes" : "**no**"} |\n`;
writeFileSync("docs/balance-strategy.md", md);
console.log(md); console.error(`total ${((Date.now() - t0) / 1000).toFixed(0)}s`);
